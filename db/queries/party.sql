-- name: ListPeople :many
-- Keyset pagination on (created_at DESC, id DESC); the caller asks for limit+1 rows to
-- learn whether a next page exists. `q` is matched token by token against the folded
-- normalized_name so the trigram index can serve it.
SELECT p.id, p.first_name, p.middle_name, p.last_name, p.status, p.created_at,
       COALESCE(mi.masked_value, '')::text AS masked_primary_identifier
  FROM party.person p
  LEFT JOIN LATERAL (
       SELECT i.masked_value
         FROM party.person_identifier i
        WHERE i.tenant_id = p.tenant_id AND i.person_id = p.id AND i.is_primary
        ORDER BY i.created_at
        LIMIT 1) mi ON true
 WHERE p.tenant_id = $1
   AND (sqlc.narg('status')::text IS NULL OR p.status = sqlc.narg('status')::text)
   AND (sqlc.narg('q')::text IS NULL
        OR p.normalized_name LIKE ALL (
             SELECT '%' || token || '%'
               FROM unnest(string_to_array(sqlc.narg('q')::text, ' ')) AS token))
   AND (sqlc.narg('sponsor_id')::uuid IS NULL
        OR EXISTS (SELECT 1
                     FROM party.sponsor_membership m
                    WHERE m.tenant_id = p.tenant_id
                      AND m.person_id = p.id
                      AND m.sponsor_tenant_organization_id = sqlc.narg('sponsor_id')::uuid
                      AND m.status = 'ACTIVE'))
   AND (sqlc.narg('cursor_created_at')::timestamptz IS NULL
        OR (p.created_at, p.id) < (sqlc.narg('cursor_created_at')::timestamptz, sqlc.narg('cursor_id')::uuid))
 ORDER BY p.created_at DESC, p.id DESC
 LIMIT sqlc.arg('page_size');

