-- name: GetPersonRelationship :one
SELECT r.id, r.source_person_id, r.target_person_id, r.relationship_type, r.status,
       lower(r.valid_period)::date AS valid_from, upper(r.valid_period)::date AS valid_to,
       r.end_reason_code, r.row_version, t.is_directional
  FROM party.person_relationship r
  JOIN party.relationship_type t ON t.tenant_id = r.tenant_id AND t.code = r.relationship_type
 WHERE r.tenant_id = $1 AND r.id = $2;

-- name: ListPersonRelationships :many
-- Both directions in one page; the other person is joined in as a summary.
SELECT r.id, r.source_person_id, r.target_person_id, r.relationship_type, r.status,
       lower(r.valid_period)::date AS valid_from, upper(r.valid_period)::date AS valid_to,
       r.end_reason_code, r.row_version, t.is_directional,
       o.id AS other_person_id, o.first_name AS other_first_name, o.middle_name AS other_middle_name,
       o.last_name AS other_last_name, o.status AS other_status,
       COALESCE(mi.masked_value, '')::text AS other_masked_identifier
  FROM party.person_relationship r
  JOIN party.relationship_type t ON t.tenant_id = r.tenant_id AND t.code = r.relationship_type
  JOIN party.person o ON o.tenant_id = r.tenant_id
       AND o.id = CASE WHEN r.source_person_id = $2 THEN r.target_person_id ELSE r.source_person_id END
  LEFT JOIN LATERAL (
       SELECT i.masked_value
         FROM party.person_identifier i
        WHERE i.tenant_id = o.tenant_id AND i.person_id = o.id AND i.is_primary
        ORDER BY i.created_at
        LIMIT 1) mi ON true
 WHERE r.tenant_id = $1 AND (r.source_person_id = $2 OR r.target_person_id = $2)
 ORDER BY r.created_at DESC, r.id DESC;

-- name: EndPersonRelationship :one
UPDATE party.person_relationship
   SET valid_period = daterange(lower(valid_period), sqlc.arg('ends_on')::date, '[)'),
       status = 'ENDED',
       end_reason_code = sqlc.arg('reason_code'),
       end_reason_text = sqlc.narg('reason_text')
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND row_version = sqlc.arg('row_version')
RETURNING row_version;

