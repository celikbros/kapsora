-- name: CreateVoucher :one
-- Only the digest and the masked tail are written. The plaintext exists in the issue
-- response and nowhere else: not in a column, not in a log line, not in an audit row.
INSERT INTO service.voucher (
    tenant_id, authorization_id, token_hash, token_masked, valid_from, valid_to, issued_by)
VALUES (sqlc.arg('tenant_id'), sqlc.arg('authorization_id'), sqlc.arg('token_hash'),
        sqlc.arg('token_masked'), sqlc.arg('valid_from'), sqlc.arg('valid_to'),
        sqlc.narg('actor_id'))
RETURNING id, status, issued_at, created_at, row_version;

-- name: GetVoucherByTokenHash :one
-- Redemption looks the voucher up by digest, never by the token itself, so the plaintext
-- never becomes a query parameter that a statement log could keep.
SELECT v.id, v.authorization_id, v.token_masked, v.valid_from, v.valid_to, v.status,
       v.redeemed_at, v.redeemed_by_actor_id, v.issued_at, v.created_at, v.row_version
  FROM service.voucher v
  JOIN service.authorization a
    ON a.tenant_id = v.tenant_id AND a.id = v.authorization_id
  JOIN service.service_request r
    ON r.tenant_id = a.tenant_id AND r.id = a.request_id
 WHERE v.tenant_id = sqlc.arg('tenant_id')
   AND v.token_hash = sqlc.arg('token_hash')
   AND (sqlc.narg('scope_ids')::uuid[] IS NULL
        OR r.provider_tenant_organization_id = ANY(sqlc.narg('scope_ids')::uuid[]))
   FOR UPDATE OF v;

-- name: ListVouchers :many
SELECT v.id, v.authorization_id, v.token_masked, v.valid_from, v.valid_to, v.status,
       v.redeemed_at, v.redeemed_by_actor_id, v.issued_at, v.created_at, v.row_version
  FROM service.voucher v
 WHERE v.tenant_id = sqlc.arg('tenant_id')
   AND v.authorization_id = sqlc.arg('authorization_id')
 ORDER BY v.issued_at DESC, v.id DESC;

-- name: CountLiveVouchers :one
-- How many vouchers for this authorization are still usable. Issuing takes the
-- authorization's row lock first, so this count cannot change underneath the check that
-- reads it; uq_voucher_one_live_per_authorization is the guarantee, and this is only how
-- the caller is told which of its two clicks arrived second.
SELECT count(*)
  FROM service.voucher
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND authorization_id = sqlc.arg('authorization_id')
   AND status = 'ISSUED';

-- name: RedeemVoucher :execrows
UPDATE service.voucher
   SET status = 'REDEEMED', redeemed_at = sqlc.arg('redeemed_at'),
       redeemed_by_actor_id = sqlc.narg('actor_id')
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND status = 'ISSUED';

-- name: ListExpiringAuthorizations :many
-- The authorizations whose validity ends on one particular day, with the member behind
-- them. It is a day and not a window because the reminder is published once per
-- authorization per expiry day: the job's deduplication key carries the same date, so an
-- hourly sweep of the same day writes one message and twenty-three no-ops.
SELECT a.id, a.authorization_reference, a.valid_to, r.person_id
  FROM service.authorization a
  JOIN service.service_request r ON r.tenant_id = a.tenant_id AND r.id = a.request_id
 WHERE a.tenant_id = sqlc.arg('tenant_id')
   AND a.status IN ('ACTIVE','PARTIALLY_USED')
   AND a.valid_to >= sqlc.arg('day_start')
   AND a.valid_to < sqlc.arg('day_end')
 ORDER BY a.valid_to, a.id
 LIMIT sqlc.arg('page_size');
