-- name: FreezeServiceRequestVersion :execrows
-- Submitting freezes the version: the snapshot is the header and the lines exactly as they
-- were sent, and tg_request_version_guard makes every later write to this row fail.
UPDATE service.service_request_version
   SET status        = 'SUBMITTED',
       snapshot_json = sqlc.arg('snapshot_json'),
       submitted_at  = sqlc.arg('submitted_at'),
       submitted_by  = sqlc.narg('actor_id')
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND status = 'DRAFT';

-- name: SupersedeServiceRequestVersion :execrows
-- The one update a submitted version accepts: it is marked as replaced by a later one and
-- nothing else about it changes.
UPDATE service.service_request_version
   SET status = 'SUPERSEDED'
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND status = 'SUBMITTED';

-- name: ListServiceRequestItems :many
SELECT id, service_request_version_id, line_no, service_definition_id,
       requested_quantity::text AS requested_quantity,
       unit_type,
       -- A NULL amount renders as the empty string rather than as a NULL text: the caller
       -- turns it back into "no value", and no cast anywhere invents a zero.
       COALESCE(requested_amount::text, '')::text  AS requested_amount,
       currency_code, status,
       COALESCE(approved_quantity::text, '')::text AS approved_quantity,
       COALESCE(approved_amount::text, '')::text   AS approved_amount,
       decision_reason_code
  FROM service.service_request_item
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND service_request_version_id = sqlc.arg('service_request_version_id')
 ORDER BY line_no;

-- name: DeleteServiceRequestItems :execrows
-- Only a draft version's lines can be deleted; tg_request_item_guard refuses the rest.
DELETE FROM service.service_request_item
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND service_request_version_id = sqlc.arg('service_request_version_id');

