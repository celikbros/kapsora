-- Service request queries (WP-I4-01, v1.2 9.11, 11.8, 11.9).
--
-- Two properties shape this file. The first is that nothing here writes `status` as a
-- field a caller chose: every statement that moves a request is named after the command
-- that moves it, carries that command's precondition in its WHERE clause and sets the
-- reason columns the transition owes. A generic "set the status to whatever was sent" is
-- exactly the statement this package exists to not have.
--
-- The second is the provider boundary. `scope_ids` is a nullable uuid[]: NULL means the
-- caller is tenant-wide, a non-null array binds it to those organizations. It is applied
-- in every read of a request, including the single-row ones, so a provider asking for
-- another provider's request finds no row and is answered 404 rather than 403 — that such
-- a request exists at all is somebody else's business.
--
-- Quantities and amounts are read as `::text` and written as `::text::numeric`, so an
-- exact decimal never passes through a float in either direction (handbook section 3).

-- name: CreateServiceRequest :one
-- Opens a request in DRAFT. The reference is generated by the caller and unique per
-- tenant; a collision surfaces as a unique violation and is retried with a new one.
INSERT INTO service.service_request (
    tenant_id, request_reference, request_type, person_id, program_id, enrollment_id,
    provider_tenant_organization_id, service_date, requested_start_at, requested_end_at,
    channel, supersedes_request_id, created_by, updated_by)
VALUES (sqlc.arg('tenant_id'), sqlc.arg('request_reference'), sqlc.arg('request_type'),
        sqlc.arg('person_id'), sqlc.arg('program_id'), sqlc.arg('enrollment_id'),
        sqlc.narg('provider_tenant_organization_id'), sqlc.arg('service_date'),
        sqlc.narg('requested_start_at'), sqlc.narg('requested_end_at'),
        sqlc.arg('channel'), sqlc.narg('supersedes_request_id'),
        sqlc.narg('actor_id'), sqlc.narg('actor_id'))
RETURNING id, request_reference, created_at, row_version;

-- name: GetServiceRequest :one
SELECT r.id, r.request_reference, r.request_type, r.person_id, r.program_id, r.enrollment_id,
       r.provider_tenant_organization_id, r.service_date, r.requested_start_at, r.requested_end_at,
       r.channel, r.status, r.current_version_no, r.supersedes_request_id,
       r.eligibility_evaluation_id, r.rule_evaluation_id, r.required_document_types,
       r.return_reason_code, r.reject_reason_code, r.review_comment,
       r.submitted_at, r.closed_at, r.created_at, r.row_version,
       concat_ws(' ', p.first_name, p.middle_name, p.last_name) AS person_display_name,
       o.display_name AS provider_display_name
  FROM service.service_request r
  JOIN party.person p ON p.tenant_id = r.tenant_id AND p.id = r.person_id
  LEFT JOIN directory.tenant_organization po
       ON po.tenant_id = r.tenant_id AND po.id = r.provider_tenant_organization_id
  LEFT JOIN directory.organization o ON o.id = po.organization_id
 WHERE r.tenant_id = sqlc.arg('tenant_id')
   AND r.id = sqlc.arg('id')
   AND (sqlc.narg('scope_ids')::uuid[] IS NULL
        OR r.provider_tenant_organization_id = ANY(sqlc.narg('scope_ids')::uuid[]));

-- name: LockServiceRequest :one
-- The same read taken FOR UPDATE, so two commands on one request serialise instead of
-- racing each other into two different decisions.
SELECT r.id, r.request_reference, r.request_type, r.person_id, r.program_id, r.enrollment_id,
       r.provider_tenant_organization_id, r.service_date, r.requested_start_at, r.requested_end_at,
       r.channel, r.status, r.current_version_no, r.supersedes_request_id,
       r.eligibility_evaluation_id, r.rule_evaluation_id, r.required_document_types,
       r.return_reason_code, r.reject_reason_code, r.review_comment,
       r.submitted_at, r.closed_at, r.created_at, r.row_version,
       concat_ws(' ', p.first_name, p.middle_name, p.last_name) AS person_display_name,
       o.display_name AS provider_display_name
  FROM service.service_request r
  JOIN party.person p ON p.tenant_id = r.tenant_id AND p.id = r.person_id
  LEFT JOIN directory.tenant_organization po
       ON po.tenant_id = r.tenant_id AND po.id = r.provider_tenant_organization_id
  LEFT JOIN directory.organization o ON o.id = po.organization_id
 WHERE r.tenant_id = sqlc.arg('tenant_id')
   AND r.id = sqlc.arg('id')
   AND (sqlc.narg('scope_ids')::uuid[] IS NULL
        OR r.provider_tenant_organization_id = ANY(sqlc.narg('scope_ids')::uuid[]))
   -- `OF r` and not a bare FOR UPDATE: two commands on one request must serialise, and
   -- nothing about that should take a lock on the member's own row or on an organization
   -- every other request in the tenant also names.
   FOR UPDATE OF r;

-- name: ListServiceRequests :many
-- Keyset pagination on (created_at DESC, id DESC); the caller asks for limit+1 rows to
-- learn whether a next page exists.
SELECT r.id, r.request_reference, r.request_type, r.person_id, r.program_id, r.enrollment_id,
       r.provider_tenant_organization_id, r.service_date, r.requested_start_at, r.requested_end_at,
       r.channel, r.status, r.current_version_no, r.supersedes_request_id,
       r.eligibility_evaluation_id, r.rule_evaluation_id, r.required_document_types,
       r.return_reason_code, r.reject_reason_code, r.review_comment,
       r.submitted_at, r.closed_at, r.created_at, r.row_version,
       concat_ws(' ', p.first_name, p.middle_name, p.last_name) AS person_display_name,
       o.display_name AS provider_display_name
  FROM service.service_request r
  JOIN party.person p ON p.tenant_id = r.tenant_id AND p.id = r.person_id
  LEFT JOIN directory.tenant_organization po
       ON po.tenant_id = r.tenant_id AND po.id = r.provider_tenant_organization_id
  LEFT JOIN directory.organization o ON o.id = po.organization_id
 WHERE r.tenant_id = sqlc.arg('tenant_id')
   AND (sqlc.narg('scope_ids')::uuid[] IS NULL
        OR r.provider_tenant_organization_id = ANY(sqlc.narg('scope_ids')::uuid[]))
   AND (sqlc.narg('status')::text IS NULL OR r.status = sqlc.narg('status')::text)
   AND (sqlc.narg('person_id')::uuid IS NULL OR r.person_id = sqlc.narg('person_id')::uuid)
   AND (sqlc.narg('program_id')::uuid IS NULL OR r.program_id = sqlc.narg('program_id')::uuid)
   AND (sqlc.narg('provider_id')::uuid IS NULL
        OR r.provider_tenant_organization_id = sqlc.narg('provider_id')::uuid)
   AND (sqlc.narg('channel')::text IS NULL OR r.channel = sqlc.narg('channel')::text)
   AND (sqlc.narg('service_date_from')::date IS NULL
        OR r.service_date >= sqlc.narg('service_date_from')::date)
   AND (sqlc.narg('service_date_to')::date IS NULL
        OR r.service_date <= sqlc.narg('service_date_to')::date)
   AND (sqlc.narg('created_from')::timestamptz IS NULL
        OR r.created_at >= sqlc.narg('created_from')::timestamptz)
   AND (sqlc.narg('created_to')::timestamptz IS NULL
        OR r.created_at <= sqlc.narg('created_to')::timestamptz)
   AND (sqlc.narg('cursor_created_at')::timestamptz IS NULL
        OR (r.created_at, r.id) < (sqlc.narg('cursor_created_at')::timestamptz, sqlc.narg('cursor_id')::uuid))
 ORDER BY r.created_at DESC, r.id DESC
 LIMIT sqlc.arg('page_size');

-- name: UpdateServiceRequestDraftHeader :execrows
-- The merge-patch of a DRAFT request's header. `status` is absent on purpose and there is
-- no statement anywhere in this file that would let a caller supply one.
UPDATE service.service_request
   SET provider_tenant_organization_id = sqlc.narg('provider_tenant_organization_id'),
       service_date       = sqlc.arg('service_date'),
       requested_start_at = sqlc.narg('requested_start_at'),
       requested_end_at   = sqlc.narg('requested_end_at'),
       updated_by         = sqlc.narg('actor_id')
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND row_version = sqlc.arg('row_version')
   AND status = 'DRAFT';

-- name: TouchServiceRequest :execrows
-- Bumps row_version without changing a business field, so replacing the lines of the
-- draft invalidates the ETag the caller is holding for the request.
UPDATE service.service_request
   SET updated_by = sqlc.narg('actor_id')
 WHERE tenant_id = sqlc.arg('tenant_id') AND id = sqlc.arg('id');

-- name: MarkServiceRequestSubmitted :execrows
-- The one write of the submit gate. It records the outcome the gate arrived at together
-- with the two evaluations that produced it, so "why is this waiting for a document"
-- always has an answer that outlives the rule version that decided it.
UPDATE service.service_request
   SET status                    = sqlc.arg('status'),
       submitted_at              = sqlc.arg('submitted_at'),
       eligibility_evaluation_id = sqlc.narg('eligibility_evaluation_id'),
       rule_evaluation_id        = sqlc.narg('rule_evaluation_id'),
       required_document_types   = sqlc.narg('required_document_types')::text[],
       review_comment            = sqlc.narg('review_comment'),
       return_reason_code        = NULL,
       updated_by                = sqlc.narg('actor_id')
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND row_version = sqlc.arg('row_version')
   AND status = 'DRAFT';

-- name: MarkServiceRequestReturned :execrows
-- Back to DRAFT with the reason it was sent back. submitted_at is cleared because the
-- schema defines a draft as a request that has not been submitted; the submission it did
-- make is on the frozen version, which is where anybody looking for it will find it.
UPDATE service.service_request
   SET status                  = 'DRAFT',
       submitted_at            = NULL,
       closed_at               = NULL,
       current_version_no      = sqlc.arg('current_version_no'),
       return_reason_code      = sqlc.arg('return_reason_code'),
       review_comment          = sqlc.narg('review_comment'),
       required_document_types = NULL,
       updated_by              = sqlc.narg('actor_id')
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND row_version = sqlc.arg('row_version')
   AND status IN ('PENDING_REVIEW', 'PENDING_DOCUMENT');

-- name: MarkServiceRequestRejected :execrows
-- A refusal is final. The request closes here and is never reopened; a further attempt is
-- a new request naming this one in supersedes_request_id.
UPDATE service.service_request
   SET status             = 'REJECTED',
       reject_reason_code = sqlc.arg('reject_reason_code'),
       review_comment     = sqlc.narg('review_comment'),
       closed_at          = sqlc.arg('decided_at'),
       updated_by         = sqlc.narg('actor_id')
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND row_version = sqlc.arg('row_version')
   AND status = 'PENDING_REVIEW';

-- name: MarkServiceRequestApproved :execrows
-- Approval and partial approval share one statement because they differ only in the word
-- and in what the lines say; both leave the request open, because nothing has been
-- authorized or delivered yet.
UPDATE service.service_request
   SET status         = sqlc.arg('status'),
       review_comment = sqlc.narg('review_comment'),
       updated_by     = sqlc.narg('actor_id')
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND row_version = sqlc.arg('row_version')
   AND status = 'PENDING_REVIEW';

-- name: MarkServiceRequestCancelled :execrows
-- Withdrawal before a decision. A request that has already been decided is not cancelled
-- here: undoing a decision has consequences of its own and belongs to service.cancellation.
UPDATE service.service_request
   SET status     = 'CANCELLED',
       closed_at  = sqlc.arg('decided_at'),
       updated_by = sqlc.narg('actor_id')
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = sqlc.arg('id')
   AND row_version = sqlc.arg('row_version')
   AND status IN ('DRAFT', 'SUBMITTED', 'PENDING_REVIEW', 'PENDING_DOCUMENT', 'ELIGIBILITY_FAILED');

-- name: CreateServiceRequestVersion :one
-- Opens the next version. The return columns are set when the version exists because it
-- was sent back: the reason belongs to the draft the requester is asked to correct, which
-- is also the only version the immutability trigger of migration 000006 lets anybody
-- write to.
INSERT INTO service.service_request_version (
    tenant_id, service_request_id, version_no, returned_at, returned_by,
    return_reason_code, return_reason_text, created_by)
VALUES (sqlc.arg('tenant_id'), sqlc.arg('service_request_id'), sqlc.arg('version_no'),
        sqlc.narg('returned_at'), sqlc.narg('returned_by'),
        sqlc.narg('return_reason_code'), sqlc.narg('return_reason_text'),
        sqlc.narg('actor_id'))
RETURNING id, version_no, status, created_at;

-- name: GetServiceRequestDraftVersion :one
