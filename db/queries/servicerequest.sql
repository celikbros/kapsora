-- name: GetServiceRequestEnrollment :one
-- The enrollment a request is raised under, with the person it belongs to and the program
-- of its plan. A request naming an enrollment that is not this person's, or not in this
-- program, is a request nobody could act on.
SELECT e.id, e.plan_id, p.program_id, e.status, m.person_id,
       lower(e.valid_period)::date AS valid_from,
       upper(e.valid_period)::date AS valid_to
  FROM benefit.enrollment e
  JOIN party.sponsor_membership m ON m.tenant_id = e.tenant_id AND m.id = e.sponsor_membership_id
  JOIN benefit.plan p ON p.tenant_id = e.tenant_id AND p.id = e.plan_id
 WHERE e.tenant_id = sqlc.arg('tenant_id') AND e.id = sqlc.arg('id');

-- name: ServiceRequestProviderOrganizationExists :one
-- The provider a request names has to be an organization this tenant deals with in a
-- provider role.
SELECT EXISTS (
    SELECT 1
      FROM directory.tenant_organization
     WHERE tenant_id = sqlc.arg('tenant_id')
       AND id = sqlc.arg('id')
       AND relationship_role = 'PROVIDER'
) AS ok;

-- name: ListServiceRequestServiceDefinitions :many
-- The definitions named by the lines, with the unit they are counted in and whether they
-- need a provider at all.
SELECT id, code, default_unit_type, requires_provider, active
  FROM catalog.service_definition
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND id = ANY(sqlc.arg('ids')::uuid[]);

-- name: ListPublishedRuleSetVersionsForPurposes :many
-- Every published rule set version of the tenant that covers the service date and serves
-- one of the given purposes. The exclusion constraint on rules.rule_set_version makes at
-- most one version per set match, so this is "which rules decide today" and never a
-- choice between two answers.
SELECT v.id, v.rule_set_id, s.code AS rule_set_code, s.purpose, v.version_no, v.input_schema
  FROM rules.rule_set_version v
  JOIN rules.rule_set s ON s.tenant_id = v.tenant_id AND s.id = v.rule_set_id
 WHERE v.tenant_id = sqlc.arg('tenant_id')
   AND v.status = 'PUBLISHED'
   AND s.status = 'ACTIVE'
   AND s.purpose = ANY(sqlc.arg('purposes')::text[])
   AND daterange(v.valid_from, v.valid_to, '[)') @> sqlc.arg('service_date')::date
 ORDER BY s.purpose, s.code, v.version_no;

-- name: GetServiceRequestReviewSetting :one
-- Whether a program's approved requests still need a person to look at them. It is a
-- setting rather than a hard-coded rule because two sponsors running the same program type
-- genuinely differ on it; the service falls back to "a person reviews it", which is the
-- answer that cannot quietly approve something nobody meant to approve.
SELECT value_json
  FROM platform.tenant_setting
 WHERE tenant_id = sqlc.arg('tenant_id')
   AND setting_key = 'service_request.review_required';

-- name: ListServiceRequestDocumentEvidence :many
-- A link alone is not proof: both the linked object and its canonical bytes must
-- still be clean and retained. Do not use another provider's attachment.
SELECT o.id, l.document_type_code
  FROM document.link l
  JOIN document.object o ON o.tenant_id = l.tenant_id AND o.id = l.object_id
  JOIN document.object stored ON stored.tenant_id = o.tenant_id
       AND stored.id = COALESCE(o.duplicate_of_object_id, o.id)
 WHERE l.tenant_id = sqlc.arg('tenant_id')
   AND l.aggregate_type = 'SERVICE_REQUEST'
   AND l.aggregate_id = sqlc.arg('request_id')
   AND l.document_type_code = ANY(sqlc.arg('required_types')::text[])
   AND o.scan_status = 'CLEAN' AND o.bucket = 'secure' AND o.purged_at IS NULL
   AND stored.scan_status = 'CLEAN' AND stored.bucket = 'secure' AND stored.purged_at IS NULL
   AND (sqlc.narg('provider_id')::uuid IS NULL OR o.owner_tenant_organization_id IS NULL
        OR o.owner_tenant_organization_id = sqlc.narg('provider_id')::uuid)
 ORDER BY l.document_type_code, o.id;
